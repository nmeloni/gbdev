SECTION "Header", ROM0[$100]

    jp EntryPoint
    ds $150 -@, 0               ; Espace pour le header Gameboy

EntryPoint:
    ;;
WaitVBlank:
    ld a, [rLY]
    cp 144
    jp c, WaitVBlank

    ;; LCD off
    ld a, 0
    ld [rLCDC], a

TitleScreen:
    ld de, Unbricked_Title_Screen_Tileset_Begin
    ld hl, $9000
    ld bc, Unbricked_Title_Screen_Tileset_End - Unbricked_Title_Screen_Tileset_Begin
    call MemCopy

    ld de, Unbricked_Title_Screen_Map_Begin
    ld hl, $9800
    ld bc, Unbricked_Title_Screen_Map_End - Unbricked_Title_Screen_Map_Begin
    call MemCopy

    ; Turn the LCD on
    ld a, LCDC_ON | LCDC_BG_ON
    ld [rLCDC], a

    ; During the first (blank) frame, initialize display registers
    ld a, %11100100
    ld [rBGP], a

TitleScreenLoop:
    call UpdateKeys
    ld a, [wCurKeys]
    and PAD_START
    jr z, TitleScreenLoop

WaitVBlank3:
    ld a, [rLY]
    cp 144
    jp c, WaitVBlank3

    ;; LCD off
    ld a, 0
    ld [rLCDC], a

    ;; Copie des tiles en VRAM Background
    ld de, Tiles
    ld hl, $9000
    ld bc, TilesEnd - Tiles
    call MemCopy

    ;; Copie de la Tilemap
    ld de, Tilemap
    ld hl, $9800
    ld bc, TilemapEnd - Tilemap
    call MemCopy

    ;; On copie le sprite du paddle en VRAM SPRITE
    ld de, Paddle
    ld hl, $8000
    ld bc, PaddleEnd - Paddle
    call MemCopy

    ;; On copie la balle en VRAM
    ld de, Ball
    ld hl, $8010
    ld bc, BallEnd - Ball
    call MemCopy

    ;; Met la memoire OAM a zero 4x40 bytes
    ld a, 0
    ld b, 160
    ld hl, STARTOF(OAM)
ClearOAM:
    ld [hl+], a
    dec b
    jp nz, ClearOAM

    ;; On place un premier objet dans l'OAM
    ;; En memoire 4 bytes par objet
    ;; ---------------------
    ;; | Y | X | ID | Prop |
    ;; ---------------------

    ld hl, STARTOF(OAM)
    ld a, 128 + 16              ; Premier pixel visible a la coordonne Y = 16
    ld [hl+], a
    ld a, 16 + 8                ; Premier pixel visible a la coodonne  X = 8
    ld [hl+], a
    ld a, 0
    ld [hl+], a
    ld [hl+], a

    ;; On place la balle en OAM
    ld a, 100 + 16
    ld [hl+], a
    ld a, 32 + 8
    ld [hl+], a
    ld a, 1                     ;Attention ID tile different !!
    ld [hl+], a
    ld a, 0
    ld [hl+], a

    ;; La balle demarre avec la direction haut/droite
    ld a, 1
    ld [wBallMomentumX], a
    ld a, -1
    ld [wBallMomentumY], a

    ;; LCD ON
    ld a, LCDC_ON | LCDC_BG_ON | LCDC_OBJ_ON
    ld [rLCDC], a

    ;; Met a jour la palette BKG et SPRITE
    ld a, %11100100
    ld [rBGP], a
    ld a, %11100100
    ld [rOBP0], a

    ;; Init les variables globales
    ld a, 0
    ld [wFrameCounter], a
    ld [wCurKeys], a
    ld [wNewKeys], a
    ld [wScore], a

Main:
    ;; On attend que VBlank soit terminé
    ld a, [rLY]
    cp 144
    jp nc, Main
WaitVBlank2:
    ld a, [rLY]
    cp 144
    jp c, WaitVBlank2

    call BallUpdate
    ;; On check les inputs
    call UpdateKeys

    ;; On commence par verifier si la direction gauche est pressee
CheckLeft:
    ld a, [wCurKeys]
    and a, PAD_LEFT
    jp  z, CheckRight
Left:
    ld a, [STARTOF(OAM)+1]
    dec a
    ;; On teste le bord gauche
    cp a, 15
    jp z, Main
    ld [STARTOF(OAM) + 1], a
    jp Main
    ;; On verifie la direction droite
CheckRight:
    ld a, [wCurKeys]
    and a, PAD_RIGHT
    jp z, Main
Right:
    ld a, [STARTOF(OAM) + 1]
    inc a
    ;;  teste bord droit
    cp a, 105
    jp z, Main
    ld [STARTOF(OAM) + 1], a
    jp Main

    ld a, [wFrameCounter]
    inc a
    ld [wFrameCounter], a
    cp a, 15
    jp nz, Main

    ld a, 0
    ld [wFrameCounter], a
    ;; On déplace le Paddle
    ld a, [STARTOF(OAM)+1]      ;adresse du registre de position X de l'objet
    inc a
    ld [STARTOF(OAM)+1], a
    jp Main

IncreaseScorePackedBCD::
    ld hl, wScore       ; load score address for faster access
    ld a, [hl]          ; load score to accumulator
    add 1
    daa                 ; make sure it's a BCD
    ld [hl], a          ; store score
    call UpdateScoreBoard
    ret

UpdateScoreBoard:
    ld a, [wScore]
    and %11110000
    swap a
    add a, DIGIT_OFFSET
    ld [SCORE_TENS], a

    ld a, [wScore]
    and %00001111
    add a, DIGIT_OFFSET
    ld [SCORE_ONES], a
    ret





